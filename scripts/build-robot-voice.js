#!/usr/bin/env node
/**
 * Build docs/lib/robot-voice.js - Conductor's built-in robot (meSpeak/eSpeak) voice.
 *
 * WHY: the app must stay one ~2-3 MB HTML file that can be AirDropped around, so the
 * ~1.5 MB speech engine ships gzipped + base64 inside a plain string and is only
 * inflated and evaluated (by docs/js/robotVoice.js) when an event needs the voice.
 *
 * Reads the mespeak@2.0.2 devDependency from node_modules, drops its page 'unload'
 * listener (blocks the back/forward cache), wraps engine + config + en-us voice in one
 * function body, gzips it and writes window.ROBOT_VOICE_GZ_B64. Deterministic output.
 *
 * Usage: node scripts/build-robot-voice.js [--check]
 */
'use strict';

const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const repoRoot = path.resolve(__dirname, '..');
const outPath = path.join(repoRoot, 'docs', 'lib', 'robot-voice.js');
const UNLOAD_LINE = "if (typeof window !== 'undefined') window.addEventListener('unload', unloadHandler, false);";

const HEADER = `/*
 * Conductor built-in robot voice. GENERATED by scripts/build-robot-voice.js - do not edit by hand.
 *
 * Contains (gzip + base64): meSpeak 1.9.6 (npm "mespeak" 2.0.2) by Norbert Landsteiner,
 * https://www.masswerk.at/mespeak/ - based on speak.js by Alon Zakai
 * (https://github.com/kripken/speak.js), an Emscripten port of eSpeak by Jonathan Duddington
 * (https://espeak.sourceforge.net/), with its US-English voice.
 * License: GNU General Public License v3 or later. Corresponding source: the npm package
 * mespeak@2.0.2 (https://www.npmjs.com/package/mespeak, https://github.com/mikolalysenko/mespeak);
 * the only change is removing one window 'unload' listener (see the build script). See THIRD_PARTY.md.
 *
 * Only defines a string. docs/js/robotVoice.js inflates and runs it when an event needs the voice.
 */
`;

function fail(msg) {
    throw new Error(msg);
}

function parseJson(text, label) {
    try {
        return JSON.parse(text);
    } catch (e) {
        return fail(label + ' is not valid JSON: ' + e.message);
    }
}

function build() {
    const pkgJsonPath = require.resolve('mespeak/package.json', { paths: [repoRoot] });
    const pkgDir = path.dirname(pkgJsonPath);
    const pkg = parseJson(fs.readFileSync(pkgJsonPath, 'utf8'), 'mespeak/package.json');
    if (pkg.version !== '2.0.2') {
        fail('mespeak version is ' + pkg.version + ', expected 2.0.2 (the unload patch is version-specific)');
    }

    const read = (rel) => fs.readFileSync(path.join(pkgDir, rel), 'utf8');
    const espeak = read(path.join('src', 'ESpeak.js'));
    let indexJs = read(path.join('src', 'index.js'));
    const configText = read(path.join('src', 'mespeak_config.json')).trim();
    const voiceText = read(path.join('voices', 'en', 'en-us.json')).trim();

    const config = parseJson(configText, 'mespeak_config.json');
    for (const f of ['config', 'phontab', 'phonindex', 'phondata', 'intonations']) {
        if (typeof config[f] !== 'string') fail('mespeak_config.json lacks string field "' + f + '"');
    }
    const voice = parseJson(voiceText, 'en-us.json');
    for (const f of ['voice_id', 'voice']) {
        if (typeof voice[f] !== 'string') fail('en-us.json lacks string field "' + f + '"');
    }

    if (indexJs.split(UNLOAD_LINE).length !== 2) fail('unload listener line not found exactly once in index.js');
    indexJs = indexJs.replace(UNLOAD_LINE, '');
    if (!indexJs.includes('require("./ESpeak.js")')) fail('index.js does not require ./ESpeak.js as expected');
    if (!espeak.trimStart().startsWith('module.exports = function ESpeak()')) fail('ESpeak.js has an unexpected start');

    const body = [
        'var __espeakModule = { exports: {} };',
        '(function (module, exports) {',
        espeak,
        '})(__espeakModule, __espeakModule.exports);',
        'var __mespeakModule = { exports: {} };',
        '(function (module, exports, require) {',
        indexJs,
        '})(__mespeakModule, __mespeakModule.exports, function (name) {',
        "  if (name === './ESpeak.js') return __espeakModule.exports;",
        "  throw new Error('robot-voice: unexpected require ' + name);",
        '});',
        'var meSpeak = __mespeakModule.exports;',
        'meSpeak.loadConfig(' + configText + ');',
        'meSpeak.loadVoice(' + voiceText + ');',
        'return meSpeak;',
        '',
    ].join('\n');

    const gz = zlib.gzipSync(Buffer.from(body, 'utf8'), { level: 9 });
    const output = HEADER + 'window.ROBOT_VOICE_GZ_B64 = "' + gz.toString('base64') + '";\n';
    return { output, body, bodyBytes: Buffer.byteLength(body, 'utf8'), gzBytes: gz.length };
}

function main() {
    const { output, body, bodyBytes, gzBytes } = build();
    const kb = (n) => (n / 1024).toFixed(1) + ' KB';

    if (process.argv.includes('--check')) {
        // Compare what the file DECODES to, not its gzip bytes: zlib builds
        // differ between Node versions, so identical inputs can gzip differently.
        const current = fs.existsSync(outPath) ? fs.readFileSync(outPath, 'utf8') : '';
        const m = current.match(/^([\s\S]*)window\.ROBOT_VOICE_GZ_B64 = "([A-Za-z0-9+/=]+)";\r?\n$/);
        let same = false;
        if (m && m[1].replace(/\r\n/g, '\n') === HEADER) { // tolerate a CRLF checkout
            try { same = zlib.gunzipSync(Buffer.from(m[2], 'base64')).toString('utf8') === body; } catch (e) { same = false; }
        }
        if (same) {
            console.log('robot-voice.js is up to date');
            return;
        }
        console.log('robot-voice.js is stale - run node scripts/build-robot-voice.js');
        process.exit(1);
    }

    fs.mkdirSync(path.dirname(outPath), { recursive: true });
    fs.writeFileSync(outPath, output, 'utf8');
    console.log('raw body: ' + kb(bodyBytes));
    console.log('gzip:     ' + kb(gzBytes));
    console.log('output:    ' + kb(Buffer.byteLength(output, 'utf8')));
    console.log('wrote ' + path.relative(repoRoot, outPath).split(path.sep).join('/'));
}

try {
    main();
} catch (e) {
    console.error('build-robot-voice failed: ' + e.message);
    process.exit(1);
}
